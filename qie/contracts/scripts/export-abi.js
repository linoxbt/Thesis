// Writes the ABIs the app needs to ../app/lib/abi.ts (run after `hardhat compile`).
const fs = require("node:fs");
const path = require("node:path");
const art = (p) => JSON.parse(fs.readFileSync(path.join(__dirname, "..", "artifacts", "contracts", p), "utf8")).abi;
const calls = art("ThesisCalls.sol/ThesisCalls.json");
const feed = art("ThesisCalls.sol/IPriceFeed.json");
const out = `// Generated by qie/contracts/scripts/export-abi.js from the compiled contracts. Do not edit.
export const THESIS_CALLS_ABI = ${JSON.stringify(calls, null, 2)} as const;

export const PRICE_FEED_ABI = ${JSON.stringify(feed, null, 2)} as const;

export const ERC20_ABI = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
] as const;
`;
fs.mkdirSync(path.join(__dirname, "..", "..", "app", "lib"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "..", "..", "app", "lib", "abi.ts"), out);
console.log("wrote qie/app/lib/abi.ts");
